/*
 * 运动曲线模块：
 * 当前只提供一个 Q15 格式的余弦衰减系数，用于电机软停止。
 * Q15 的满量程约为 32767，调用方用 当前转速 * 系数 / 32767 得到平滑下降转速。
 */
